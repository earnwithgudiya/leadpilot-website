-- LeadPilot additive migration: activity history
-- SAFE: creates a new table and triggers only. Does not delete or rewrite public.leads rows.
-- Run once in Supabase SQL Editor. Keep RLS enabled on public.leads.

create table if not exists public.lead_activities (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  lead_id text,
  lead_name text not null default 'Lead',
  activity_type text not null check (activity_type in ('created','updated','deleted')),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists lead_activities_user_created_idx
  on public.lead_activities (user_id, created_at desc);

alter table public.lead_activities enable row level security;

drop policy if exists "Users can view their own lead activity" on public.lead_activities;
create policy "Users can view their own lead activity"
  on public.lead_activities for select to authenticated
  using (auth.uid() = user_id);

-- No client INSERT/UPDATE/DELETE policies are intentionally provided.
-- A database trigger writes activity rows after authenticated lead changes.

create or replace function public.capture_lead_activity()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid;
  v_lead_id text;
  v_lead_name text;
  v_type text;
  v_details jsonb;
begin
  if tg_op = 'DELETE' then
    v_user_id := old.user_id;
    v_lead_id := old.id::text;
    v_lead_name := coalesce(old.name, 'Lead');
    v_type := 'deleted';
    v_details := jsonb_build_object('summary', 'Lead removed from the workspace');
    insert into public.lead_activities(user_id, lead_id, lead_name, activity_type, details)
    values (v_user_id, v_lead_id, v_lead_name, v_type, v_details);
    return old;
  elsif tg_op = 'INSERT' then
    v_user_id := new.user_id;
    v_lead_id := new.id::text;
    v_lead_name := coalesce(new.name, 'Lead');
    v_type := 'created';
    v_details := jsonb_build_object('summary', 'New lead added');
    insert into public.lead_activities(user_id, lead_id, lead_name, activity_type, details)
    values (v_user_id, v_lead_id, v_lead_name, v_type, v_details);
    return new;
  else
    v_user_id := new.user_id;
    v_lead_id := new.id::text;
    v_lead_name := coalesce(new.name, 'Lead');
    v_type := 'updated';
    v_details := jsonb_build_object(
      'summary', case
        when old.status is distinct from new.status then 'Status changed: ' || coalesce(old.status,'—') || ' → ' || coalesce(new.status,'—')
        when old.follow_up_date is distinct from new.follow_up_date then 'Follow-up date changed'
        when old.notes is distinct from new.notes then 'Lead notes updated'
        else 'Lead details updated'
      end,
      'status_changed', old.status is distinct from new.status,
      'follow_up_date_changed', old.follow_up_date is distinct from new.follow_up_date,
      'notes_changed', old.notes is distinct from new.notes
    );
    insert into public.lead_activities(user_id, lead_id, lead_name, activity_type, details)
    values (v_user_id, v_lead_id, v_lead_name, v_type, v_details);
    return new;
  end if;
end;
$$;

drop trigger if exists lead_activity_after_insert on public.leads;
create trigger lead_activity_after_insert
  after insert on public.leads
  for each row execute function public.capture_lead_activity();

drop trigger if exists lead_activity_after_update on public.leads;
create trigger lead_activity_after_update
  after update on public.leads
  for each row execute function public.capture_lead_activity();

drop trigger if exists lead_activity_after_delete on public.leads;
create trigger lead_activity_after_delete
  after delete on public.leads
  for each row execute function public.capture_lead_activity();

grant select on public.lead_activities to authenticated;
